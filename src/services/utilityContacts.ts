/** 주소 첫 낱말 → 짧은 시도 이름 */
const SIDO: Array<[RegExp, string]> = [
  [/^서울/, '서울'], [/^부산/, '부산'], [/^대구/, '대구'], [/^인천/, '인천'], [/^광주/, '광주'], [/^대전/, '대전'], [/^울산/, '울산'], [/^세종/, '세종'],
  [/^경기/, '경기'], [/^강원/, '강원'], [/^충(청)?북/, '충북'], [/^충(청)?남/, '충남'], [/^전(라)?북|^전북/, '전북'], [/^전(라)?남/, '전남'],
  [/^경(상)?북/, '경북'], [/^경(상)?남/, '경남'], [/^제주/, '제주'],
];

/** '경기도 성남시 분당구 …' → { sido: '경기', sigungu: '성남', place: '성남시' } */
export const regionOf = (address: string) => {
  const words = String(address ?? '').trim().split(/\s+/);
  const sido = SIDO.find(([re]) => re.test(words[0] ?? ''))?.[1] ?? '';
  const place = words[1] ?? '';
  const sigungu = place.replace(/(특별자치)?(시|군|구)$/, '');
  return { sido, sigungu, place };
};

/** 도시가스 후보 — 전체 공급 회사가 있으면 그것, 없으면 일부 공급 회사들 */
export const gasOf = (address: string): Array<{ name: string; phone: string; partial: boolean }> => {
  const { sido, sigungu } = regionOf(address);
  if (!sido) return [];
  const hit = (m?: Record<string, string[]>) => !!m?.[sido] && (m[sido].includes('*') || m[sido].includes(sigungu));
  const full = GAS.filter((g) => hit(g.full)).map((g) => ({ name: g.name, phone: g.phone, partial: false }));
  const part = GAS.filter((g) => hit(g.part)).map((g) => ({ name: g.name, phone: g.phone, partial: true }));
  return full.length && !part.length ? full : [...full, ...part];
};

const METRO = ['서울', '부산', '대구', '인천', '광주', '대전', '울산', '세종'];

/** 공과금 줄 글 — 물건 주소로 채운다 */
export const utilityLine = (rowId: string, address: string): string | null => {
  const { sido, place } = regionOf(address);
  // 특별 · 광역시 · 세종은 시 상수도사업본부가, 도는 시 · 군 상수도사업소가 맡는다
  if (rowId === 'ev.util.w2') {
    const who = METRO.includes(sido) ? `${sido}시 상수도사업본부` : place ? `${place} 상수도사업소` : '물건지 상수도사업소';
    return `연락처 — ${who} · 국번없이 121`;
  }
  if (rowId === 'ev.util.g3') {
    const list = gasOf(address);
    if (!list.length) return '연락처 — 물건지 도시가스 회사 콜센터';
    const txt = list.map((g) => `${g.name} ${g.phone}`).join(' / ');
    return `연락처 — ${txt}${list.length > 1 ? ' (구역이 나뉜 곳이라 주소로 확인)' : ''}`;
  }
  return null;
};
